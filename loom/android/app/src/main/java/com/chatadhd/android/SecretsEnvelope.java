package com.chatadhd.android;

import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.Key;
import java.util.Arrays;

import javax.crypto.Cipher;
import javax.crypto.spec.GCMParameterSpec;

/**
 * Pure-Java (no android.* imports, so it is testable with plain javac; see verify/)
 * on-disk format for the Keystore-sealed secrets file.
 *
 * <pre>
 *   "LSK1" | ivLen (1 byte) | iv | AES-256-GCM ciphertext + 16-byte tag
 * </pre>
 *
 * The key is supplied by the caller: on a phone it is the non-exportable AES key held by the
 * Android Keystore (see SecretsVault.kt), in the host test it is a plain software key. The IV is
 * always generated by the provider (the Keystore insists on that), never by this code. The magic
 * and a fixed context string are bound in as additional authenticated data, so a sealed blob
 * cannot be passed off as some other file and the header cannot be altered without detection.
 */
public final class SecretsEnvelope {
    private SecretsEnvelope() {}

    private static final byte[] MAGIC = {'L', 'S', 'K', '1'};
    // AAD = magic || context string: the header and the purpose of the blob are authenticated.
    private static final byte[] AAD = concat(MAGIC, "chatadhd.secrets.v1".getBytes(StandardCharsets.US_ASCII));
    private static final int TAG_BITS = 128;

    private static byte[] concat(byte[] a, byte[] b) {
        byte[] r = Arrays.copyOf(a, a.length + b.length);
        System.arraycopy(b, 0, r, a.length, b.length);
        return r;
    }

    /** The blob is not in this format (wrong magic, truncated, impossible IV length). */
    public static final class FormatException extends GeneralSecurityException {
        private static final long serialVersionUID = 1L;
        public FormatException(String m) { super(m); }
    }

    /** Cheap check used to tell a sealed file from the plain JSON the core writes. */
    public static boolean looksSealed(byte[] blob) {
        if (blob == null || blob.length < MAGIC.length + 1) return false;
        for (int i = 0; i < MAGIC.length; i++) if (blob[i] != MAGIC[i]) return false;
        return true;
    }

    public static byte[] seal(Key key, byte[] plain) throws GeneralSecurityException {
        Cipher c = Cipher.getInstance("AES/GCM/NoPadding");
        c.init(Cipher.ENCRYPT_MODE, key);
        c.updateAAD(AAD);
        byte[] iv = c.getIV();
        if (iv == null || iv.length == 0 || iv.length > 255) throw new GeneralSecurityException("provider returned no usable IV");
        byte[] ct = c.doFinal(plain);
        byte[] out = new byte[MAGIC.length + 1 + iv.length + ct.length];
        System.arraycopy(MAGIC, 0, out, 0, MAGIC.length);
        out[MAGIC.length] = (byte) iv.length;
        System.arraycopy(iv, 0, out, MAGIC.length + 1, iv.length);
        System.arraycopy(ct, 0, out, MAGIC.length + 1 + iv.length, ct.length);
        return out;
    }

    public static byte[] unseal(Key key, byte[] blob) throws GeneralSecurityException {
        if (!looksSealed(blob)) throw new FormatException("not a sealed secrets file");
        int ivLen = blob[MAGIC.length] & 0xff;
        int ivStart = MAGIC.length + 1;
        int ctStart = ivStart + ivLen;
        if (ivLen == 0 || blob.length < ctStart + TAG_BITS / 8) throw new FormatException("truncated sealed secrets file");
        Cipher c = Cipher.getInstance("AES/GCM/NoPadding");
        c.init(Cipher.DECRYPT_MODE, key, new GCMParameterSpec(TAG_BITS, Arrays.copyOfRange(blob, ivStart, ctStart)));
        c.updateAAD(AAD);
        return c.doFinal(blob, ctStart, blob.length - ctStart);
    }
}
