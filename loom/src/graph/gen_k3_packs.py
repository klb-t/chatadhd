#!/usr/bin/env python3
"""Embed the K3-1 packs (graph/dimensions.pack, graph/address_syntax.pack) and pin them in data/data_domains.pack.

  gen_k3_packs.py          write src/graph/k3_packs_embedded.inc and refresh the sha256 pins
  gen_k3_packs.py --check  fail when either is stale

The .inc holds each pack as std::string_view(R"...", N) with an explicit length (CLAUDE.md: clang's constexpr step limit stops bare
literals measured by strlen; gcc accepts them). The runtime reads <data_dir>/graph/*.pack first when it exists and falls back to this copy.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKS = [
    ("graph/dimensions.pack", "loom.dimensions/1", "kDimensionsPack"),
    ("graph/address_syntax.pack", "loom.address_syntax/1", "kAddressSyntaxPack"),
]
DELIM = "loompack"
REFS = ["loom/tests/test_address.cpp", "loom/tests/test_dimensions.cpp"]
DOMAIN = "graph_address"


def read(rel):
    return (ROOT / "data" / rel).read_bytes()


def inc():
    out = ["// Generated by src/graph/gen_k3_packs.py from data/graph/dimensions.pack and data/graph/address_syntax.pack. Do not edit.\n",
           "#pragma once\n#include <string_view>\n"]
    for rel, schema, name in PACKS:
        raw = read(rel)
        doc = json.loads(raw)
        assert doc["schema"] == schema, rel
        text = raw.decode("utf-8")
        assert f'){DELIM}"' not in text
        out.append(f'inline constexpr std::string_view {name}(R"{DELIM}({text}){DELIM}", {len(raw)});\n')
    return "".join(out)


def pinned():
    path = ROOT / "data" / "data_domains.pack"
    doc = json.loads(path.read_text(encoding="utf-8"))
    files = [f for f in doc["files"] if f["path"] not in {p[0] for p in PACKS}]
    for rel, schema, _ in PACKS:
        files.append({"path": rel, "schema": schema, "sha256": hashlib.sha256(read(rel)).hexdigest(), "domain": DOMAIN,
                      "role": "configuration", "validation_refs": REFS})
    doc["files"] = files
    return path, json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    target = ROOT / "src/graph/k3_packs_embedded.inc"
    want = inc()
    dpath, dwant = pinned()
    if args.check:
        stale = [str(p) for p, w in ((target, want), (dpath, dwant)) if not p.exists() or p.read_text(encoding="utf-8") != w]
        if stale:
            sys.exit("stale: " + ", ".join(stale) + " (run src/graph/gen_k3_packs.py)")
        return
    target.write_text(want, encoding="utf-8")
    dpath.write_text(dwant, encoding="utf-8")


if __name__ == "__main__":
    main()
