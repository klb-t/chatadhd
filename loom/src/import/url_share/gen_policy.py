#!/usr/bin/env python3
"""Generate/check the bootstrap preset; no shared pack generator changes."""
from pathlib import Path
import json
import sys
root = Path(__file__).resolve().parents[3]
source = root / "data/presets/url_share.pack"
target = Path(__file__).with_name("policy.inc")
doc = json.loads(source.read_text())
output = '// Generated by gen_policy.py from data/presets/url_share.pack.\n' + 'constexpr const char* kPolicy = R"URLPOLICY(' + json.dumps(doc, ensure_ascii=True, indent=2) + ')URLPOLICY";\n'
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != output:
        sys.exit("url policy generated copy differs")
else:
    target.write_text(output)
