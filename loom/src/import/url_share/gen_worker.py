#!/usr/bin/env python3
"""Reproducible embedding of the single canonical worker.py; no runtime path."""
import base64
import hashlib
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent

def render(raw):
    encoded = base64.b64encode(raw).decode('ascii')
    lines = ['// Generated by gen_worker.py from canonical worker.py; do not edit.',
             'constexpr std::string_view kWorkerBase64 =']
    lines += ['    "' + encoded[i:i + 76] + '"' for i in range(0, len(encoded), 76)]
    lines += ['    ;', 'constexpr std::string_view kWorkerSha256 = "' + hashlib.sha256(raw).hexdigest() + '";']
    return ('\n'.join(lines) + '\n').encode('ascii')

if __name__ == '__main__':
    output = render((HERE / 'worker.py').read_bytes())
    target = HERE / 'worker.inc'
    if '--check' in sys.argv:
        if not target.exists() or target.read_bytes() != output:
            sys.exit('embedded URL worker differs from canonical bytes')
    else:
        target.write_bytes(output)
