#!/usr/bin/env python3
"""Generate data/graph/interfaces.pack: the interface registry shown by the graph entry view.

Entries are read from the real sources, never typed by hand:
  c_abi - every LOOM_API function declared in include/loom/loom.h
  http  - every "/api/..." route registered in server/src (METHOD path)
  cli   - not listed here: counted live from the `cli` runtime profile (/commands)
Usage: gen_graph_interfaces.py [--check]   (--check fails when the pack is stale)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'data/graph/interfaces.pack'


def c_abi():
    text = (ROOT / 'include/loom/loom.h').read_text(encoding='utf-8')
    names = re.findall(r'LOOM_API\s+[^;(]*?\b(loom_\w+)\s*\(', text)
    return sorted(set(names))


def http_routes():
    found = set()
    for path in sorted((ROOT / 'server/src').glob('*.[ch]*')):
        for m in re.finditer(r'\.(Get|Post|Put|Patch|Delete)\(\s*"(/api/[^"]*)"', path.read_text(encoding='utf-8')):
            found.add(f'{m.group(1).upper()} {m.group(2)}')
    return sorted(found)


def build():
    return {
        'schema': 'loom.graph_interfaces/1',
        'revision': 1,
        'description': 'Interface registry for the graph entry view, generated by tools/gen_graph_interfaces.py from '
                       'loom.h and the server route registrations. Do not edit by hand. The cli entry is counted live '
                       'from the cli runtime profile. Overlay profiles/graph_entry.pack may add interfaces or set hidden:true.',
        'interfaces': {
            'c_abi': {'label': {'en': 'C ABI (loom.h)', 'pl': 'C ABI (loom.h)'}, 'entries': c_abi()},
            'http': {'label': {'en': 'HTTP API', 'pl': 'API HTTP'}, 'entries': http_routes()},
            'cli': {'label': {'en': 'Command line', 'pl': 'Wiersz poleceń'},
                    'from': {'domain': 'cli', 'pointer': '/commands'}},
        },
    }


def main():
    text = json.dumps(build(), indent=2, ensure_ascii=False) + '\n'
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            print('stale: run tools/gen_graph_interfaces.py', file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
