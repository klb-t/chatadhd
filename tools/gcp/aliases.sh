#!/usr/bin/env bash
# HTTPS aliases on port 443 for services on this VM: each service gets its own hostname (no ports, no subpaths),
# Caddy terminates TLS with Let's Encrypt. Free and account-less by default: <alias>.<ip-with-dashes>.sslip.io
# (sslip.io resolves the IP encoded in the name). With a domain of your own: --domain example.org → <alias>.example.org.
#   sudo bash tools/gcp/aliases.sh [--domain D] [--ip IP] [--dry-run]
# The list below is a preset (open): alias | upstream on loopback | auth (none = the app has its own login;
# optional 4th field: where / redirects (e.g. noVNC's page); optional 5th: a snippet to import into the site block,
# skipped while the file does not exist (e.g. the guest wall deployed by tools/gcp/deploy_guests.sh); basic = Caddy basic auth, password generated once into /etc/caddy/aliases.pass, printed by --show-pass).
# Needs inbound 80+443 (firewall) for the certificates; until then Caddy keeps retrying on its own.
set -euo pipefail
ALIASES=(
  "chat|127.0.0.1:8787|none||/etc/caddy/chatadhd-guests.caddy"
  "watchdog|127.0.0.1:8080|basic"
  "desktop|127.0.0.1:6080|basic|/vnc.html?autoconnect=true&resize=remote"
  "ageds|127.0.0.1:8090|basic"
)
DOMAIN="" IP="" DRY=0 SHOW=0
while [ $# -gt 0 ]; do case "$1" in
  --domain) DOMAIN="$2"; shift 2;; --ip) IP="$2"; shift 2;; --dry-run) DRY=1; shift;; --show-pass) SHOW=1; shift;;
  *) sed -n '2,9p' "$0"; exit 2;; esac; done
PASSF=/etc/caddy/aliases.pass
if [ "$SHOW" = 1 ]; then sudo cat "$PASSF"; exit 0; fi
IP="${IP:-$(curl -s -m 3 -H 'Metadata-Flavor: Google' http://metadata.google.internal/computeMetadata/v1/instance/network-interfaces/0/access-configs/0/external-ip)}"
BASE="${DOMAIN:-${IP//./-}.sslip.io}"
command -v caddy >/dev/null || sudo apt-get install -y -qq caddy
sudo mkdir -p /etc/caddy
if ! sudo test -s "$PASSF"; then
  pw="$(head -c 18 /dev/urandom | base64 | tr -d '/+=' | head -c 20)"
  printf 'user: marcin\npassword: %s\n' "$pw" | sudo tee "$PASSF" >/dev/null; sudo chmod 600 "$PASSF"
fi
# Caddy < 2.8 (Ubuntu ships 2.6) knows only "basicauth"
BA=basic_auth; printf "%s\n2.8\n" "$(caddy version | grep -oE '[0-9]+\.[0-9]+' | head -1)" | sort -V -C && BA=basicauth
pw="$(sudo sed -n 's/^password: //p' "$PASSF")"; hash="$(caddy hash-password --plaintext "$pw")"
out="# generated by tools/gcp/aliases.sh $(date -u +%FT%TZ) — edit the list in the script, not this file\n"
for a in "${ALIASES[@]}"; do
  IFS='|' read -r name up auth root snip <<<"$a"
  out+="\n$name.$BASE {\n  encode zstd gzip\n"
  [ "$auth" = basic ] && out+="  $BA {\n    marcin $hash\n  }\n"
  [ -n "${root:-}" ] && out+="  redir / ${root} 302\n"
  [ -n "${snip:-}" ] && sudo test -f "$snip" && out+="  import $snip\n"
  out+="  reverse_proxy $up\n}\n"
done
if [ "$DRY" = 1 ]; then printf "%b" "$out"; exit 0; fi
printf "%b" "$out" | sudo tee /etc/caddy/Caddyfile >/dev/null
sudo caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
sudo systemctl enable --now caddy >/dev/null 2>&1; sudo systemctl reload caddy
for a in "${ALIASES[@]}"; do echo "https://${a%%|*}.$BASE"; done
echo "hasło basic auth: sudo bash $0 --show-pass"
