#!/usr/bin/env python3
"""Embed the tested worker so native does not depend on a checkout path."""
from pathlib import Path
import argparse
root = Path(__file__).resolve().parents[2]
source = root / 'loom/src/media/local_ocr_worker.py'
target = root / 'loom/src/media/local_ocr_worker.inc'
text = '// Generated by tools/m1/embed_local_ocr.py; do not edit.\n'
text += '[[maybe_unused]] constexpr std::string_view kLocalOcrWorker = R"LOOM_OCR(' + source.read_text() + ')LOOM_OCR";\n'
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
args = p.parse_args()
if args.check:
    assert target.read_text() == text, 'stale embedded OCR worker'
else:
    target.write_text(text)
